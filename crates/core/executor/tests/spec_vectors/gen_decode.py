#!/usr/bin/env python3
"""Emit `lean/ZirenDet/ZirenDet/IsaDecode.lean` from `decoded.json` (the executor's own decoding of
every vector word, produced by `SPEC_DUMP_DECODED=... cargo test --test spec_vectors`): one
`example` per distinct word checking that the Lean decoder, lowered to the executor's internal
form, agrees with `Instruction::decode_from`."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.abspath(os.path.join(here, "..", "..", "..", "..", ".."))
d = json.load(open(os.path.join(here, "decoded.json")))
out = ["import ZirenDet.Isa", "",
       "/-! Generated by `gen_decode.py`: the executor's decoding (`Instruction::decode_from`) of every",
       "spec-vector word, checked against the Lean decoder lowered to the executor's internal form. -/", "",
       "namespace ZirenDet.IsaDecode", "open ZirenDet.Isa", ""]
n = 0
for word, f in sorted(d.items()):
    if "error" in f:
        continue
    b = "true" if f["imm_b"] else "false"
    c = "true" if f["imm_c"] else "false"
    out.append(f"/-- {f['opcode_name']} -/")
    out.append(f"example : decodeInternal 0x{word}#32 = some ⟨{f['opcode']}, {f['op_a']}, {f['op_b']}, {f['op_c']}, {b}, {c}⟩ := by")
    out.append("  native_decide")
    out.append("")
    n += 1
out.append("end ZirenDet.IsaDecode")
path = os.path.join(repo, "lean", "ZirenDet", "ZirenDet", "IsaDecode.lean")
open(path, "w").write("\n".join(out) + "\n")
print(f"wrote {n} decode checks to {path}")
